# Clean text
def clean_text(text):
    if pd.isna(text):
        return ""
    text = unescape(str(text))
    return re.sub(r'\s+', ' ', text).strip()

# Process dataset
for col in df.columns:
    df[col] = df[col].apply(clean_text)

df = df.dropna(subset=['Dish-Name', 'Instructions']).reset_index(drop=True)

# Format for training
