import numpy as np
from rouge_score import rouge_scorer
from nltk.translate.bleu_score import sentence_bleu, SmoothingFunction
from nltk.translate.meteor_score import meteor_score
from nltk.tokenize import word_tokenize
import textstat
import time

class RecipeEvaluator:
    def __init__(self, model, tokenizer):
        self.model = model
        self.tokenizer = tokenizer
        self.rouge_scorer = rouge_scorer.RougeScorer(['rouge1', 'rouge2', 'rougeL'], use_stemmer=True)
        self.smoothing = SmoothingFunction()

    def calculate_metrics(self, predictions, references):
        # BLEU scores
        bleu_scores = []
        for pred, ref in zip(predictions, references):
            pred_tokens = word_tokenize(pred.lower())
            ref_tokens = word_tokenize(ref.lower())
            score = sentence_bleu([ref_tokens], pred_tokens, smoothing_function=self.smoothing.method1)
            bleu_scores.append(score)

        # ROUGE scores
        rouge1_scores = []
        rouge2_scores = []
        rougeL_scores = []
        for pred, ref in zip(predictions, references):
            scores = self.rouge_scorer.score(ref, pred)
            rouge1_scores.append(scores['rouge1'].fmeasure)
            rouge2_scores.append(scores['rouge2'].fmeasure)
            rougeL_scores.append(scores['rougeL'].fmeasure)

        # METEOR scores
        meteor_scores = []
        for pred, ref in zip(predictions, references):
            pred_tokens = word_tokenize(pred.lower())
            ref_tokens = word_tokenize(ref.lower())
            score = meteor_score([ref_tokens], pred_tokens)
            meteor_scores.append(score)

        # Perplexity
        perplexities = []
        for text in predictions:
            inputs = self.tokenizer(text, return_tensors="pt", truncation=True, max_length=512)
            with torch.no_grad():
                outputs = self.model(**inputs, labels=inputs["input_ids"])
                perplexity = torch.exp(outputs.loss).item()
                perplexities.append(min(perplexity, 1000))  # Cap at 1000

        return {
            'bleu_mean': np.mean(bleu_scores),
            'rouge1_mean': np.mean(rouge1_scores),
            'rouge2_mean': np.mean(rouge2_scores),
            'rougeL_mean': np.mean(rougeL_scores),
            'meteor_mean': np.mean(meteor_scores),
            'perplexity_mean': np.mean(perplexities)
        }

    def run_evaluation(self):
        print("🔬 Running Evaluation...")

        # Test dishes
        test_dishes = [
            {"name": "Jollof Rice", "about": "West African rice dish", "ingredients": "Rice, tomatoes, spices"},
            {"name": "Ugali", "about": "East African staple", "ingredients": "Cornmeal, water"},
            {"name": "Injera", "about": "Ethiopian bread", "ingredients": "Teff flour, water"},
            {"name": "Egusi Soup", "about": "Nigerian soup", "ingredients": "Melon seeds, spinach"},
            {"name": "Bobotie", "about": "South African dish", "ingredients": "Beef, curry, bread"}
        ]

        predictions = []
        references = []

        for dish in test_dishes:
            pred = generate_african_recipe(dish['name'], dish['about'], dish['ingredients'])
            predictions.append(pred)

            ref = f"{dish['name']} is a {dish['about']} made with {dish['ingredients']}"
            references.append(ref)

        results = self.calculate_metrics(predictions, references)

        # Model stats
        total_params = sum(p.numel() for p in self.model.parameters())
        trainable_params = sum(p.numel() for p in self.model.parameters() if p.requires_grad)

        print("\n📊 EVALUATION RESULTS")
        print("=" * 40)
        print(f"BLEU Score:      {results['bleu_mean']:.4f}")
        print(f"ROUGE-1:         {results['rouge1_mean']:.4f}")
        print(f"ROUGE-2:         {results['rouge2_mean']:.4f}")
        print(f"ROUGE-L:         {results['rougeL_mean']:.4f}")
        print(f"METEOR:          {results['meteor_mean']:.4f}")
        print(f"Perplexity:      {results['perplexity_mean']:.2f}")
        print(f"\nTotal Parameters:     {total_params:,}")
        print(f"Trainable Parameters: {trainable_params:,}")
        print(f"Parameter Efficiency: {(trainable_params/total_params)*100:.2f}%")

        return results

# Run evaluation
evaluator = RecipeEvaluator(model, tokenizer)
results = evaluator.run_evaluation()

