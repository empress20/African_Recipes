from trl import SFTTrainer, SFTConfig
from transformers import TrainerCallback
import time

class MetricsCallback(TrainerCallback):
    def __init__(self):
        super().__init__()
        self.training_loss = []
        self.steps = []
        self.epoch_loss = []
        self.epochs = []
        self.learning_rates = []
        self.start_time = time.time()
        self.step_times = []

    def on_log(self, args, state, control, logs=None, **kwargs):
        if logs:
            if 'loss' in logs:
                self.training_loss.append(logs['loss'])
                self.steps.append(state.global_step)
                self.step_times.append(time.time() - self.start_time)
            if 'learning_rate' in logs:
                self.learning_rates.append(logs['learning_rate'])
            if state.global_step % 50 == 0 and 'loss' in logs:
                elapsed = time.time() - self.start_time
                print(f"Step {state.global_step}: Loss = {logs['loss']:.4f}, Time = {elapsed:.1f}s")

    def on_epoch_end(self, args, state, control, **kwargs):
        if self.training_loss:
            steps_per_epoch = max(1, len(self.training_loss) // max(1, int(state.num_train_epochs)))
            recent_losses = self.training_loss[-steps_per_epoch:]
            avg_loss = sum(recent_losses) / len(recent_losses) if recent_losses else 0
            self.epoch_loss.append(avg_loss)
            self.epochs.append(state.epoch)
            elapsed = time.time() - self.start_time
            print(f"\n🎯 Epoch {state.epoch} completed: Average Loss = {avg_loss:.4f}, Time = {elapsed/60:.1f} min")

callback = MetricsCallback()
train_dataset = Dataset.from_pandas(cleaned_df)

# Training configuration
