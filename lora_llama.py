import re
from html import unescape
import unicodedata

def clean_dataset(df):
    print("🧹 Cleaning dataset...")

    def clean_text(text):
        if pd.isna(text):
            return ""
        text = str(text)
        text = unescape(text)
        text = unicodedata.normalize('NFKD', text)
        text = text.replace('½', '1/2').replace('¼', '1/4').replace('¾', '3/4')
        text = re.sub(r'\s+', ' ', text).strip()
        return text

    df = df.copy()
    for col in df.columns:
        df[col] = df[col].apply(clean_text)

    possible_name_cols = [c for c in df.columns if any(name in c.lower() for name in ['dish-name', 'dish_name', 'dish', 'name', 'title', 'recipe'])]
    possible_instr_cols = [c for c in df.columns if any(instr in c.lower() for instr in ['instructions', 'instruction', 'steps', 'method', 'directions', 'preparation'])]

    if not possible_name_cols:
        raise ValueError('Could not find dish name column')
    if not possible_instr_cols:
        raise ValueError('Could not find instructions column')

    name_col = possible_name_cols[0]
    instr_col = possible_instr_cols[0]

    initial_count = len(df)
    df = df.dropna(subset=[name_col, instr_col])
    df = df[df[instr_col].str.len() > 50]
    df = df[df[name_col].str.len() > 2]
    df = df.drop_duplicates(subset=[name_col])
    print(f"📊 Filtered from {initial_count} to {len(df)} recipes")

    def clean_instructions(instructions):
        instructions = re.sub(r'STEP\s*(\d+)', r'Step \1:', instructions, flags=re.IGNORECASE)
        instructions = re.sub(r'Step\s*(\d+)(?!:)', r'Step \1:', instructions, flags=re.IGNORECASE)
        instructions = re.sub(r'(\d+)\.', r'Step \1:', instructions)

        sentences = re.split(r'(?<=[.!?])\s+', instructions)
        cleaned_sentences = []
        for sentence in sentences:
            sentence = sentence.strip()
            if len(sentence) > 200:
                parts = re.split(r'\s+(and then|then|meanwhile|after that|next|finally|lastly)\s+', sentence, flags=re.IGNORECASE)
                for part in parts:
                    part = part.strip()
                    if len(part) > 10:
                        cleaned_sentences.append(part)
            elif len(sentence) > 10:
                cleaned_sentences.append(sentence)
        cleaned = '. '.join(s.rstrip('.').strip() for s in cleaned_sentences if s.strip())
        if cleaned and not cleaned.endswith(('.', '!', '?')):
            cleaned += '.'
        return cleaned

    df[instr_col] = df[instr_col].apply(clean_instructions)

    formatted_data = []
    for _, row in df.iterrows():
        dish_name = row[name_col]
        instruction = f"Generate a complete recipe for {dish_name}."

        about_cols = [c for c in df.columns if any(about in c.lower() for about in ['about', 'description', 'origin', 'type'])]
        if about_cols and pd.notna(row[about_cols[0]]) and row[about_cols[0]].strip():
            instruction += f"\nAbout: {row[about_cols[0]][:200]}"

        ing_cols = [c for c in df.columns if any(ing in c.lower() for ing in ['ingredients', 'ingredient', 'ings', 'items'])]
        if ing_cols and pd.notna(row[ing_cols[0]]) and row[ing_cols[0]].strip():
            instruction += f"\nIngredients: {row[ing_cols[0]][:400]}"

        cuisine_cols = [c for c in df.columns if any(cuisine in c.lower() for cuisine in ['cuisine', 'category', 'region', 'country'])]
        if cuisine_cols and pd.notna(row[cuisine_cols[0]]) and row[cuisine_cols[0]].strip():
            instruction += f"\nCuisine: {row[cuisine_cols[0]][:100]}"

        response = f"# {dish_name}\n\n"
        if ing_cols and pd.notna(row[ing_cols[0]]):
            response += f"**Ingredients:**\n{row[ing_cols[0]]}\n\n"
        response += f"**Instructions:**\n{row[instr_col]}"

        formatted_text = (
            "<|begin_of_text|><|start_header_id|>user<|end_header_id|>\n\n" +
            instruction +
            "<|eot_id|><|start_header_id|>assistant<|end_header_id|>\n\n" +
            response +
            "<|eot_id|>"
        )
        formatted_data.append({'text': formatted_text})

    result_df = pd.DataFrame(formatted_data)
    print(f"✅ Created {len(result_df)} formatted training examples")
    return result_df

