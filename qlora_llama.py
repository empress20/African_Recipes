# --- define generation function depending on loader ---
def generate_with_loaded(prompt, max_new_tokens=300, temperature=0.7, top_p=0.9):
    try:
        # prepare prompt exactly as your training format (optional)
        if prompt.strip() == "":
            return "Please enter a recipe prompt (e.g., 'How to make Jollof Rice')"
        full_prompt = prompt if prompt.strip().startswith("### Instruction:") else f"### Instruction:\n{prompt}\n\n### Response:\n"

        # If model is unsloth type (FastLanguageModel)
        if loader_used == "unsloth" or (model.__class__.__module__.startswith("unsloth") if model is not None else False):
            inputs = tokenizer([full_prompt], return_tensors="pt", truncation=True, max_length=512)
            inputs = {k: v.to(next(model.parameters()).device) for k, v in inputs.items()}
            with torch.no_grad():
                outputs = model.generate(
                    **inputs,
                    max_new_tokens=max_new_tokens,
                    temperature=temperature,
                    top_p=top_p,
                    do_sample=True,
                    pad_token_id=getattr(tokenizer, "eos_token_id", None) or tokenizer.pad_token_id
                )
            # unsloth generate may return different shapes
            try:
                input_len = inputs["input_ids"].shape[1]
                generated_tokens = outputs[0][input_len:]
            except Exception:
                generated_tokens = outputs[0]
            text = tokenizer.decode(generated_tokens, skip_special_tokens=True)
            return text

        # Else assume transformers model
        else:
            device = model.device if hasattr(model, "device") else next(model.parameters()).device
            inputs = tokenizer(full_prompt, return_tensors="pt", truncation=True, max_length=512).to(device)
            with torch.no_grad():
                outputs = model.generate(
                    **inputs,
                    max_new_tokens=max_new_tokens,
                    temperature=temperature,
                    top_p=top_p,
                    do_sample=True,
                    pad_token_id=tokenizer.eos_token_id if tokenizer.eos_token_id is not None else tokenizer.pad_token_id
                )
            return tokenizer.decode(outputs[0], skip_special_tokens=True)
    except Exception as e:
        return f"Generation error:\n{e}\n\n{traceback.format_exc()}"

