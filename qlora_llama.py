        print(f"{'ROUGE-2':<20} {results['rouge2_mean']:<12.4f} {results['rouge2_std']:<12.4f}")
        print(f"{'ROUGE-L':<20} {results['rougeL_mean']:<12.4f} {results['rougeL_std']:<12.4f}")
