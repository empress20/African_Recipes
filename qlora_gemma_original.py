import gradio as gr

def gradio_generate_recipe(dish_name, about="", ingredients=""):
    try:
        recipe = generate_recipe(dish_name, about, ingredients)
        return recipe
    except Exception as e:
        return f"Error: {str(e)}"

with gr.Blocks() as demo:
    gr.Markdown("## 🍲 African Recipe Generator")
    gr.Markdown("Generate authentic African recipes with your fine-tuned Gemma model.")

    with gr.Row():
        dish = gr.Textbox(label="Dish Name", placeholder="Egusi Soup")
    with gr.Row():
        about = gr.Textbox(label="About the Dish", placeholder="Traditional Nigerian soup")
    with gr.Row():
        ingredients = gr.Textbox(label="Ingredients", placeholder="Melon seeds, spinach")

    output = gr.Textbox(label="Generated Recipe")

    generate_btn = gr.Button("Generate Recipe")

    generate_btn.click(
        fn=gradio_generate_recipe,
        inputs=[dish, about, ingredients],
        outputs=output
    )

demo.launch(share=True)